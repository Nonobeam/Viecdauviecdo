// 10. UTILITY FUNCTIONS
const utils = {
  getJobsByCompany: (companyId) => {
    return jobs.filter((job) => job.companyId === companyId)
  },

  getCandidatesByCompany: (companyId) => {
    const companyApplications = applications.filter((app) => app.companyId === companyId)
    return companyApplications.map((app) => {
      const candidate = candidates.find((c) => c.id === app.candidateId)
      const job = jobs.find((j) => j.id === app.jobId)
      return {
        ...candidate,
        ...app,
        jobTitle: job?.title,
        jobDepartment: job?.department,
      }
    })
  },

  getApplicationsByJob: (jobId) => {
    return applications.filter((app) => app.jobId === jobId)
  },

  getApplicationsByCandidate: (candidateId) => {
    return applications.filter((app) => app.candidateId === candidateId)
  },
}

